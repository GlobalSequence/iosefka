    public:
        Metronome(uint16_t* audio_buf, metro_struct m_s) { 
            audio_buf_ = audio_buf;
            m_s_ = m_s;
            // stepNumberFunc_ = func; 
            // last_step_ = stepNumberFunc_();
            last_step_ = m_s_.stepNumberFunction();
            size_lo_ = sizeof(click_wave_lo);
            size_hi_ = sizeof(click_wave_hi);
            
        }

        void renderClick() {

            this->listenForNextClick();
            this->generateClick();   

        }

    private:
        uint16_t* audio_buf_;
        metro_struct m_s_;
        // metroStepNumberFunc stepNumberFunc_;
        int16_t last_step_;
        size_t size_lo_, size_hi_;
        click_enum current_click_ = CLICK_NONE;
        uint16_t samples_left_ = 0;
        uint16_t sample_count_ = 0;
        const uint16_t* click_buf_ptr = NULL;

        void listenForNextClick() {

            // int16_t current_step = stepNumberFunc_();
            int16_t current_step = m_s_.stepNumberFunction();

            if(current_step != last_step_) {

                last_step_ = current_step;

                if(current_step % CLICK_LO_INTERVAL == 0) {

                    if(current_step % CLICK_HI_INTERVAL == 0) {

                        current_click_ = CLICK_HI;
                        samples_left_ = size_hi_;
                        click_buf_ptr = click_wave_hi;

                    } else {

                        current_click_ = CLICK_LO;
                        samples_left_ = size_lo_;
                        click_buf_ptr = click_wave_lo;

                    }

                } else {

                    current_click_ = CLICK_NONE;
                    samples_left_ = 0;
                    return;

                }

            }

        }

        void generateClick() {

            for(int i = 0; i < audio_size; i++) {

                if(samples_left_) {

                    audio_buf_[i] = click_buf_ptr[sample_count_] >> 4; 
                    sample_count_++;
                    samples_left_--;

                } else {

                    audio_buf_[i] = 0;
                    sample_count_ = 0;

                }

            }

        }

